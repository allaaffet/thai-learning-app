function choice(
  id: string,
  prompt: string,
  options: string[],
  answerIndex: number,
  explanation: string,
  relatedConcepts: string[],
  type: "multiple-choice" | "character-recognition" = "multiple-choice",
  difficulty: 1 | 2 | 3 = 1,
): Exercise {
  return {
    id,
    type,
    prompt,
    options: options.map((label, index) => ({ id: `${id}-${index}`, label })),
    answerId: `${id}-${answerIndex}`,
    explanation,
    relatedConcepts,
    difficulty,
  };
}

