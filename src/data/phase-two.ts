import type { Chapter, Exercise, Lesson } from "@/lib/content-types";
import { vowelPatterns } from "@/data/alphabet";

/** Unicode照合は字形・文字名に限る。言語情報は教材案として残す。 */
const sourceIds = ["unicode-16-phase2"];

function choice(
  id: string,
  prompt: string,
  options: string[],
  answerIndex: number,
  explanation: string,
  relatedConcepts: string[],
  type: "multiple-choice" | "character-recognition" = "multiple-choice",
  difficulty: 1 | 2 | 3 = 1,
): Exercise {
  return {
    id,
    type,
    prompt,
    options: options.map((label, index) => ({ id: `${id}-${index}`, label })),
    answerId: `${id}-${answerIndex}`,
    explanation,
    relatedConcepts,
    difficulty,
  };
}

function vowelLesson(input: {
  id: string;
  number: number;
  title: string;
  subtitle: string;
  prerequisite: string;
  objectives: string[];
  concepts: { title: string; paragraphs: string[] }[];
  vowelIds: string[];
  exercises: Exercise[];
  summary: string[];
}): Lesson {
  const vowels = input.vowelIds.map((id) => {
    const vowel = vowelPatterns.find((entry) => entry.id === id);
    if (!vowel) throw new Error(`母音資料がありません: ${id}`);
    return vowel;
  });
  return {
    id: input.id,
    chapterId: "chapter-3",
    number: input.number,
    title: input.title,
    subtitle: input.subtitle,
    durationMinutes: 12,
    xp: 40,
    prerequisites: [input.prerequisite],
    objectives: input.objectives,
    blocks: [
      ...input.concepts.map((block, index) => ({
        id: `${input.id}-block-${index}`,
        ...block,
      })),
      {
        id: `${input.id}-examples`,
        title: "文字を、意味のある語と結び付ける",
        paragraphs: [
          "母音だけのIPAには声調を付けません。下の単語は音節全体の読みを示しています。母音の長短に加え、声調や末子音も異なる場合があります。",
        ],
        examples: vowels
          .filter((vowel) => vowel.length !== "short")
          .slice(0, 4)
          .map((vowel) => vowel.example),
      },
      {
        id: `${input.id}-limits`,
        title: "図の形と、実際の単語を分けて読む",
        paragraphs: [
          "母音パターンの - は子音を置く場所で、単語には書きません。母音記号が何個あっても、それぞれを別々の音節として読むわけではありません。",
          "末子音の有無や単語によって形が変わることがあります。未知の綴りを単純な規則だけで断定せず、文字ノートの注記と辞書で確認しましょう。音声での確認と一般的な声調判定は、今後の学習範囲です。",
        ],
      },
    ],
    explore: vowels.map((vowel) => ({
      id: `${input.id}-${vowel.id}`,
      thai: vowel.pattern,
      ipa: vowel.ipa,
      meaning: `${vowel.length === "short" ? "短母音" : vowel.length === "long" ? "長母音" : "特殊・変化形"}：${vowel.example.meaning}`,
      note: `${vowel.note} 用例：${vowel.example.thai} ${vowel.example.ipa}。${vowel.example.note ?? ""}`,
    })),
    exercises: input.exercises,
    summary: input.summary,
    relatedLessonIds: [input.prerequisite, "vowel-length"],
    sourceIds,
    verification: "unreviewed",
  };
}

