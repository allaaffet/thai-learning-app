function vowel(
  id: string,
  pattern: string,
  ipa: string,
  length: VowelPattern["length"],
  position: VowelPattern["position"],
  example: ExampleSentence,
  note: string,
  pairId?: string,
): VowelPattern {
  return {
    id,
    pattern,
    ipa,
    length,
    position,
    ...(pairId ? { pairId } : {}),
    example,
    note,
    sourceIds,
    verification: "unreviewed",
  };
}

