interface CharacterOptions {
  introducedInLessonIds?: string[];
  usage?: AlphabetCharacter["usage"];
  note?: string;
  alternateInitialIpa?: string[];
}

function consonant(
  id: string,
  thai: string,
  unicodeSuffix: string,
  name: string,
  meaning: string,
  consonantClass: ConsonantClass,
  initialIpa: string,
  finalIpa: string | undefined,
  example: ExampleSentence,
  options: CharacterOptions = {},
): AlphabetCharacter {
  // 字母名の最初の音節は長い /ɔː/。語中での子音音とは別の欄に持つ。
  const nameTone = consonantClass === "high" ? "˩˩˦" : "˧";
  return {
    id,
    thai,
    name,
    ipa: `/${initialIpa.slice(1, -1)}ɔː${nameTone}/`,
    meaning,
    consonantClass,
    initialIpa,
    ...(finalIpa ? { finalIpa } : {}),
    example,
    sourceIds,
    verification: "unreviewed",
    group: "consonant",
    usage: options.usage ?? "common",
    unicodeName: `THAI CHARACTER ${unicodeSuffix}`,
    introducedInLessonIds: [
      ...(options.introducedInLessonIds ?? []),
      ...phase2Introductions
        .filter((introduction) => introduction.characters.includes(thai))
        .map((introduction) => introduction.lessonId),
    ],
    ...(options.note ? { note: options.note } : {}),
    ...(options.alternateInitialIpa
      ? { alternateInitialIpa: options.alternateInitialIpa }
      : {}),
  };
}

