const sourceIds = ["thai-tone-rules-phase3"];

function choice(
  id: string,
  prompt: string,
  options: [string, string, string, string, string],
  answerIndex: number,
  explanation: string,
  relatedConcepts: string[],
  difficulty: 1 | 2 | 3 = 1,
): Exercise {
  return {
    id,
    type: "multiple-choice",
    prompt,
    options: options.map((label, index) => ({ id: `${id}-${index}`, label })),
    answerId: `${id}-${answerIndex}`,
    explanation,
    relatedConcepts,
    difficulty,
  };
}

function lesson(
  input: Omit<Lesson, "durationMinutes" | "xp" | "sourceIds" | "verification">,
): Lesson {
  return {
    ...input,
    durationMinutes: 10,
    xp: 40,
    sourceIds,
    verification: "unreviewed",
  };
}

