const ipaSourceId = "wiktionary-ipa-phase4";

/** 語の綴り・IPAは語彙カタログに集約する。連続発話の縮約は表さない。 */
function example(
  wordIds: string[],
  meaning: string,
  note?: string,
): ExampleSentence {
  const words = wordIds.map((id) => {
    const entry = getVocabularyEntry(id);
    if (!entry) throw new Error(`Phase 4の例語が見つかりません: ${id}`);
    return entry;
  });
  return {
    thai: words.map((entry) => entry.thai).join(""),
    ipa: `/${words.map((entry) => entry.ipa.replace(/^\//, "").replace(/\/$/, "")).join(" ")}/`,
    meaning,
    note: `${note ? `${note} ` : ""}IPAの空白は学習用の語の区切りです。連続発話の弱化・縮約までは示しません。`,
  };
}

function choice(
  id: string,
  prompt: string,
  labels: string[],
  answerIndex: number,
  explanation: string,
  relatedConcepts: string[],
): Exercise {
  return {
    id,
    type: "multiple-choice",
    prompt,
    options: labels.map((label, index) => ({ id: `${id}-${index}`, label })),
    answerId: `${id}-${answerIndex}`,
    explanation,
    relatedConcepts,
    difficulty: 1,
  };
}

function fill(
  id: string,
  prompt: string,
  answer: string,
  explanation: string,
  relatedConcepts: string[],
): Exercise {
  return {
    id,
    type: "fill-in-the-blank",
    prompt,
    options: [{ id: `${id}-answer`, label: answer }],
    answerId: `${id}-answer`,
    acceptedAnswers: [answer],
    explanation,
    relatedConcepts,
    difficulty: 2,
  };
}

function ordering(
  id: string,
  prompt: string,
  labelsInOrder: string[],
  explanation: string,
  relatedConcepts: string[],
): Exercise {
  const tokensInOrder = labelsInOrder.map((label, index) => ({
    id: `${id}-token-${index}`,
    label,
  }));
  return {
    id,
    type: "word-ordering",
    prompt,
    options: [{ id: `${id}-answer`, label: labelsInOrder.join("") }],
    answerId: `${id}-answer`,
    tokens: [...tokensInOrder.slice(1), tokensInOrder[0]],
    answerOrder: tokensInOrder.map((token) => token.id),
    explanation,
    relatedConcepts,
    difficulty: 2,
  };
}

function lesson(
  input: Omit<Lesson, "durationMinutes" | "xp" | "sourceIds" | "verification">,
): Lesson {
  return {
    ...input,
    durationMinutes: 10,
    xp: 40,
    sourceIds: [
      ipaSourceId,
      ...(["basic-word-order", "predicates-negation", "time-aspect"].includes(
        input.id,
      )
        ? ["ud-thai-grammar-phase4"]
        : input.id === "numbers-classifiers"
          ? ["ud-thai-classifiers-phase4"]
          : []),
    ],
    verification: "unreviewed",
  };
}

function explore(id: string, wordIds: string[], meaning: string, note: string) {
  return { id, ...example(wordIds, meaning), note };
}

